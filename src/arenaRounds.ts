import type {Gender,Word} from "./data";
import {exercises} from "./practice";
import {wordTranslation,type UILang} from "./i18n";

/* Question builders for Strudli Arena. Everything comes from reviewed app data:
   the 1,177 cards (gender, photo, translation), the calm-practice exercises and
   the cinematic story glossaries. Endings are generated by fixed grammar rules. */

export type RoundKind="mix"|"articles"|"photo"|"endings"|"story"|"saved";
export type ArenaQuestion={id:string;kind:RoundKind;tag:string;prompt:string;photo?:Word;speakFirst?:string;
 choices:string[];answer:string;reveal:string;translation:string;note?:string;articleButtons?:boolean;
 /** Meaning shown while the question is open (never when it would give the answer away). */
 hint?:string};
export type StoryGloss={term:string;uk:string;en:string;story:string;title:string};

export const ROUND_SIZE=10;
export const SAVED_KEY="strudli-lesen-saved";
export const REQUEST_KEY="strudli-arena-request";

const shuffle=<T,>(arr:T[]):T[]=>{const c=[...arr];for(let i=c.length-1;i>0;i--){const j=Math.floor(Math.random()*(i+1));[c[i],c[j]]=[c[j],c[i]];}return c};
const pickOthers=<T,>(pool:T[],n:number,not:(x:T)=>boolean)=>shuffle(pool.filter(x=>!not(x))).slice(0,n);
const tr=(lang:UILang,uk:string,en:string)=>lang==="en"?en:uk;

function nouns(words:Word[]){
 return words.filter(w=>w.kind==="noun"&&w.gender&&!w.pluralOnly&&(w.acceptedArticles||[]).length<=1&&w.photo&&!/\s/.test(w.de));
}

export function mixRound(words:Word[],lang:UILang):ArenaQuestion[]{
 const pool=(["cases","verbs","listening"] as const).flatMap(m=>shuffle(exercises(m,words,lang)).filter(x=>x.choices.length===3).slice(0,8));
 return shuffle(pool).slice(0,ROUND_SIZE).map(x=>({id:x.id,kind:"mix",tag:x.tag,
  prompt:x.mode==="listening"?tr(lang,"Що ти чуєш?","What do you hear?"):x.prompt,speakFirst:x.mode==="listening"?x.audio:undefined,
  choices:shuffle(x.choices),answer:x.answer,reveal:x.mode==="listening"?x.translation:x.prompt.replace("___",x.answer),
  translation:x.mode==="listening"?x.answer:x.translation,note:x.note,hint:x.mode==="listening"?undefined:x.translation}));
}

export function articleRound(words:Word[],lang:UILang):ArenaQuestion[]{
 return shuffle(nouns(words)).slice(0,ROUND_SIZE).map(w=>({id:"art-"+w.id,kind:"articles",tag:tr(lang,"Який артикль?","Which article?"),
  prompt:w.de,photo:w,choices:["der","die","das"],answer:w.gender as Gender,reveal:w.gender+" "+w.de,
  translation:wordTranslation(w,lang),articleButtons:true,hint:wordTranslation(w,lang)}));
}

export function photoRound(words:Word[],lang:UILang):ArenaQuestion[]{
 const all=nouns(words);
 return shuffle(all).slice(0,ROUND_SIZE).map(w=>{
  const same=all.filter(x=>x.topic===w.topic&&x.de!==w.de);
  const others=pickOthers(same.length>=2?same:all,2,x=>x.de===w.de);
  const label=(x:Word)=>x.gender+" "+x.de;
  return {id:"pic-"+w.id,kind:"photo",tag:tr(lang,"Що на фото?","What is in the photo?"),prompt:tr(lang,"Обери слово","Choose the word"),photo:w,
   choices:shuffle([label(w),...others.map(label)]),answer:label(w),reveal:label(w),translation:wordTranslation(w,lang),hint:wordTranslation(w,lang)};
 });
}

const ADJECTIVES:[string,string,string][]=[["neu","новий","new"],["alt","старий","old"],["groß","великий","big"],["klein","маленький","small"],["schön","гарний","beautiful"]];
const OBJECT_TOPICS=new Set(["furniture","clothing","kitchenware","tech","housework","vehicles"]);
export function endingRound(words:Word[],lang:UILang):ArenaQuestion[]{
 const pool=nouns(words).filter(w=>OBJECT_TOPICS.has(w.topic));
 return shuffle(pool).slice(0,ROUND_SIZE).map((w,i)=>{
  const [a,aUk,aEn]=ADJECTIVES[i%ADJECTIVES.length];
  const accusative=i%2===1;
  const forms:Record<Gender,string>=accusative?{der:`einen ${a}en`,die:`eine ${a}e`,das:`ein ${a}es`}:{der:`ein ${a}er`,die:`eine ${a}e`,das:`ein ${a}es`};
  const frame=accusative?"Ich kaufe ___ "+w.de+".":"Das ist ___ "+w.de+".";
  const answer=forms[w.gender as Gender];
  return {id:"end-"+w.id,kind:"endings",tag:accusative?"AKKUSATIV · "+tr(lang,"закінчення","ending"):"NOMINATIV · "+tr(lang,"закінчення","ending"),
   prompt:frame,photo:w,choices:shuffle([forms.der,forms.die,forms.das]),answer,reveal:frame.replace("___",answer),
   translation:`${w.gender} ${w.de} — ${wordTranslation(w,lang)} · ${a} — ${lang==="en"?aEn:aUk}`,hint:`${w.de} — ${wordTranslation(w,lang)} · ${a} — ${lang==="en"?aEn:aUk}`,
   note:accusative?tr(lang,"Akkusativ після «ein»: der → einen …en, die → eine …e, das → ein …es","Accusative after “ein”: der → einen …en, die → eine …e, das → ein …es")
    :tr(lang,"Nominativ після «ein»: der → ein …er, die → eine …e, das → ein …es","Nominative after “ein”: der → ein …er, die → eine …e, das → ein …es")};
 });
}

const STOP=new Set("ein eine einen einem einer und oder aber denn dass weil als wenn ich du er sie es wir ihr ihn ihm ihnen sich der die das den dem des am im an in auf aus mit von für zu nach bei über durch so nie sehr dann dort auch nicht mehr noch schon hier jetzt bald ganz".split(" "));
type StoryData={words:Record<string,string[]>;phrases:Record<string,string[]>};
export function storyGlosses(id:string,title:string,data:StoryData):StoryGloss[]{
 const out:StoryGloss[]=[],seen=new Set<string>();
 for(const [term,v] of [...Object.entries(data.phrases),...Object.entries(data.words)]){
  const key=term.toLocaleLowerCase("de");
  if(term.includes(":")||seen.has(key)||STOP.has(key)||term.length<4||/артикль/.test(v[0]))continue;
  seen.add(key);out.push({term,uk:v[0],en:v[1],story:id,title});
 }
 return out;
}
export function glossRound(items:StoryGloss[],lang:UILang,kind:RoundKind,tag:string):ArenaQuestion[]{
 const meaning=(g:StoryGloss)=>lang==="en"?g.en:g.uk;
 return shuffle(items).slice(0,ROUND_SIZE).map((g,i)=>{
  const others=pickOthers(items,2,x=>meaning(x)===meaning(g)||x.term===g.term).map(meaning);
  return {id:kind+"-"+i+"-"+g.term,kind,tag:tag||g.title,prompt:g.term,speakFirst:g.term.replace(/…/g,""),
   choices:shuffle([meaning(g),...others]),answer:meaning(g),reveal:g.term,translation:meaning(g)};
 }).filter(q=>new Set(q.choices).size===3);
}

export function loadSaved():StoryGloss[]{
 try{const v=JSON.parse(localStorage.getItem(SAVED_KEY)||"[]");return Array.isArray(v)?v.filter(x=>x&&typeof x.term==="string"&&typeof x.uk==="string"&&typeof x.en==="string"):[]}catch{return []}
}
export function takeArenaRequest():string|null{
 try{
  const raw=localStorage.getItem(REQUEST_KEY);if(!raw)return null;localStorage.removeItem(REQUEST_KEY);
  const r=JSON.parse(raw);return r&&typeof r.story==="string"&&Date.now()-Number(r.at)<120000?r.story:null;
 }catch{return null}
}
