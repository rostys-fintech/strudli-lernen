import assert from "node:assert/strict";
import {createRound,remaining,rightAnswer,wrongAnswer,nextWord} from "../src/game.ts";
let r=createRound(["food-277","food-277"]);
assert.equal(r.pool.length,1,"Duplicate words must not enter the round");
assert.equal(r.currentId,"food-277");
assert.equal(remaining(r),1);
r=wrongAnswer(r);
assert.equal(r.streaks["food-277"],0,"Wrong at zero stays at zero");
assert.equal(r.errors["food-277"],1);
r=rightAnswer(r);
assert.equal(r.streaks["food-277"],1);
r=wrongAnswer(r);
assert.equal(r.streaks["food-277"],0,"Wrong at one removes exactly one flame");
r=rightAnswer(rightAnswer(r));
assert.equal(r.streaks["food-277"],2,"Two correct answers light two flames");
assert.equal(remaining(r),1,"Word remains until three flames");
const previousScore=r.score;
const previousAttempts=r.attempts;
r=wrongAnswer(r);
assert.equal(r.streaks["food-277"],1,"Wrong at two removes exactly one, not all flames");
assert.equal(r.score,previousScore-1,"Mistake still deducts a score point");
assert.equal(r.attempts,previousAttempts+1,"Mistake still increments attempt count");
const preserved=JSON.parse(JSON.stringify(r));
assert.equal(preserved.streaks["food-277"],1,"Existing localStorage Round.streaks stays compatible");
r=rightAnswer(rightAnswer(preserved));
assert.equal(r.streaks["food-277"],3,"Third lit flame marks the word mastered");
assert.equal(remaining(r),0);
assert.equal(r.currentId,null,"Mastered word no longer appears in current round");
assert.equal(nextWord(["a","b"],{a:3,b:2},[]),"b","Completed words are excluded from the next selection");
assert.equal(nextWord([],{},[]),null);
for(let i=0;i<100;i++){const q=createRound(["x","y","z","w"]);assert.equal(new Set(q.pool).size,4);assert.ok(q.pool.includes(q.currentId))}
console.log("Game QA passed: 0/1/2/3 flame states, -1 floor, +1 cap, persistence compatibility, score/attempts and mastery.");
