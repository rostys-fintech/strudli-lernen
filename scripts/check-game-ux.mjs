import {readFileSync} from "node:fs";
const read=p=>readFileSync(new URL(p,import.meta.url),"utf8");
const app=read("../src/App.tsx"),practice=read("../src/Practice.tsx"),css=read("../src/styles.css"),data=read("../src/data.ts");
const assert=(condition,message)=>{if(!condition)throw Error("UX regression: "+message)};
assert(app.includes('masteryStage==="none"&&(word.kind==="noun"||answered)&&<p className="wordTranslation"'),"show noun translation before der/die/das; hide the translation only while the mastered word is being carried away");
assert(!app.includes('word.usage&&!answered'),"usage context reveals answer before user responds");
assert(app.includes('className={"answerOption"'),"game buttons must use a single neutral option class");
assert(!practice.includes('style={{background:['),"practice game must not assign colors by option position");
assert(css.includes('.game .answers button.answerOption')&&css.includes('.practiceChoices button{background:#fff'),"neutral button CSS absent");
assert(app.includes('<GamePicture key={word.id}'),"game picture must reset per word");
const start=data.indexOf("export const DEMO_WORDS:Word[]=");
const arrayStart=data.indexOf("=[",start)+1;
const arrayEnd=data.indexOf("];",arrayStart);
assert(start>=0&&arrayStart>0&&arrayEnd>arrayStart,"cannot locate vocabulary JSON");
const words=JSON.parse(data.slice(arrayStart,arrayEnd+1)),nouns=words.filter(w=>w.kind==="noun");
assert(nouns.length===736&&nouns.every(w=>w.photo),"noun photo coverage broken");
assert(new Set(nouns.map(w=>w.photo)).size===736,"noun picture uniqueness broken");
for(const [word] of [["leer"],["voll"],["arm"],["sicher"]])assert(words.some(w=>w.de===word&&w.photo),"illustration missing for "+word);
assert(words.filter(w=>w.photo).length===1177,"image-backed vocabulary coverage dropped");
assert(app.includes('word.topic==="pronouns"'),"German context must be displayed before the choice for any pronoun that has it");
for(const id of ["pronouns-106","pronouns-109","pronouns-111","pronouns-120","pronouns-124"])assert(words.find(w=>w.id===id)?.usage,"Disambiguating German sentence missing: "+id);
assert(words.filter(w=>w.photo).length>=986,"photo coverage regressed");
console.log("Game UX QA passed: noun translations visible before article choice; other translations hidden until correct, 5 German hints, 736 nouns, all 1177 illustrated cards.");
