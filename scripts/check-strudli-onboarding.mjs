import assert from "node:assert/strict";
import {readFileSync} from "node:fs";

const read=path=>readFileSync(path,"utf8");
const app=read("src/App.tsx");
const home=read("src/StrudliHome.tsx");
const tour=read("src/StrudliOnboarding.tsx");
const mascot=read("src/StrudliMascot.tsx");
const css=read("src/styles.css");
const tourCss=read("src/strudli-onboarding-2026.css");
const pkg=JSON.parse(read("package.json"));

assert.match(app,/className="brandWordmark" src="\/strudli\/strudli-wordmark-transparent\.webp"/,"The approved transparent wordmark must remain in the header.");
assert.match(app,/\[tourOpen,setTourOpen\]=useState\(false\)/,"Onboarding must not open automatically, even for first-time users.");
assert.doesNotMatch(app,/STRUDLI_TOUR_KEY|localStorage\.getItem\(STRUDLI_TOUR_KEY\)/,"No first-visit forced tour state.");
assert.match(app,/tourOpen&&<StrudliOnboarding/,"Opt-in guide must remain connected.");
assert.match(home,/className="strudliLandingMascot strudliTourLaunch"/,"Big home Strudli must remain a real clickable tour entry.");
assert.match(app,/onMeetStrudli=\{replayStrudliTour\}/,"Home mascot must open the tour.");
assert.doesNotMatch(app,/className="strudliTourReplay"/,"There must be no duplicate tour launch control in Progress.");
assert.match(app,/function replayStrudliTour\(\)\{setTourOpen\(true\)\}/,"Only explicit mascot interaction may start the tour.");
assert.match(app,/function closeStrudliTour\(\)\{stopGermanAudio\(\);setTourOpen\(false\)\}/,"Closing must stop preview audio and dismiss.");
assert.match(app,/onTopics=\{\(\)=>\{closeStrudliTour\(\);navigate\("home"\)\}\}/,"Finished tour must return to Home.");
assert.match(app,/onPractice=\{\(\)=>\{closeStrudliTour\(\);navigate\("practice"\)\}\}/,"Practice action must navigate to Practice.");

const scenes=["welcome","words","reading","audio","practice","progress","ready"];
const definitions=[...tour.matchAll(/^\s*\{visual:"([^"]+)"/gm)].map(m=>m[1]);
assert.deepEqual(definitions,scenes,"Tour must cover seven real sections in the approved order.");
for(const scene of scenes)assert.ok(tour.includes('item.visual==="'+scene+'"'),"Missing useful demo for "+scene);
assert.ok(tour.includes("10 sections")&&tour.includes("10 тем"),"Tour must explain actual navigation and topic structure.");
assert.ok(tour.includes('der, die or das')&&tour.includes('card')&&tour.includes('Next'),"Vocabulary flow must reflect current app.");
assert.ok(tour.includes('onClick={()=>setWordOpened(open=>!open)}')&&tour.includes("Apfel — яблуко"),"Lesen must provide a working word-tap demonstration.");
assert.ok(tour.includes('onClick={()=>onSpeak("Guten Morgen!")}'),"Audio preview must be playable on a real gesture.");
assert.ok(app.includes('onSpeak={(text)=>{void speak(text)}}'),"Tour audio sample must be connected to established German audio engine.");
assert.ok(tour.includes('todayCorrect:number')&&tour.includes('dailyGoal:number')&&tour.includes('favoritesCount:number'),"Progress demo must reflect actual user values, not fabricated counters.");
for(const data of ['todayCorrect={todayCount}','dailyGoal={dailyGoal}','favoritesCount={favorites.length}'])assert.ok(app.includes(data),"Live tour metric not connected: "+data);
assert.match(tour,/tap the big Strudli on the home screen/,"Reopening instructions must describe mascot entry.");
assert.match(tour,/Закрити/,"Explicit close button must remain.");
assert.match(tour,/Назад/,"Back navigation must remain.");
assert.match(tour,/Далі/,"Forward navigation must remain.");
assert.match(tour,/onTopics\(\)/,"Last step must offer the real topics route.");
assert.match(tour,/onClick=\{onPractice\}/,"Last step must offer real practice route.");
assert.match(tour,/e\.key==="Escape"/,"Escape must dismiss the tour.");
assert.match(tour,/e\.key==="Tab"/,"Focus must be trapped within the dialog.");
assert.match(tour,/previousFocus\?\.isConnected\)previousFocus\.focus\(\)/,"Focus must return to the mascot after dismissal.");
assert.match(tour,/role="dialog" aria-modal="true"/,"Tour must remain an accessible modal.");
assert.ok(tour.includes('/strudli/strudli-storybook-hero.webp')&&tour.includes('strudli-wordmark-transparent.webp'),"Modern tour must reuse approved HQ Strudli and wordmark.");
for(const name of ["open-book-tab.svg","berlin-gate-photo.jpg"])assert.ok(tourCss.includes(name),"Tour must retain warm storybook style assets: "+name);
assert.ok(tour.includes('import "./strudli-onboarding-2026.css"'),"New tour CSS must be imported.");
for(const token of [".strudliTourCard--v2","strudliTourHeroMascot",".strudliTourFooter","max-width:390px","max-height:660px","prefers-reduced-motion:reduce"])assert.ok(tourCss.includes(token),"Missing accessible responsive design token: "+token);
assert.match(mascot,/strudliMascotSprite/,"Older approved mascot pose still available elsewhere in app.");
assert.match(css,/strudli-poses-approved-20261123\.png/,"Approved four-pose sheet must remain available for other exercises.");
assert.match(app,/<StrudliMascot pose="success"\/>/,"Lesson success must still show mascot.");
assert.match(css,/\.topbar \.logo \.brandWordmark/,"Full logo styling must remain.");
assert.ok(pkg.scripts["check:all"].includes("npm run check:strudli"),"Onboarding contract must run in CI.");
console.log("Strudli onboarding QA: PASS — 7 opt-in steps, actual German audio, live progress, Lesen interaction, approved design, keyboard and mobile accessibility.");
